  # აქ უნდა შეიქმნას კიდევ ერთი შვილი კლასი რომლითახ მოხდება საკრედიტო ლიმიტის განსაზღვრა და მიეთითება კვლავ მშობელი კლასის თვისებები
class CreditAccount (BankAccount):
    # აქ ვამატებთ საკრედიტო ლიმიტს მინუსში წასვლისთვის
    def __init__(self, card_type, owner, balance, credit_limit = 2000):
        super().__init__(card_type, owner, balance)
        self.credit_limit = credit_limit
# აქ ისევ გვჭირდება პოლიმორფიზმი და გადაფარვა
    def withdraw(self, amount):
# საკრედიტო ანგარიშისთვის withdraw -მა უნდა იმუშაოს სხვანაირად, შესაძლებელი უნდა იყოს საკრედიტო ლიმიტის ფარგლებში ანგარიშ ჩავარდეს მინუსში. 
        new_balance = self.balance - amount
        if amount > 0 and new_balance >= - self.credit_limit:
            # აქ სეტერის გვერდის ავლით პირდაპირ ვწერთ მინუს ბალანსს დაცულ ატრიბუტში
            self._BankAccount__balance = new_balance
            print(f" საკრედიტო ანგარიშდან მოხსნილია {amount} ლარი, მიმდინარე ბალანსი {self.balance} ლარი ")
        else:
            print("უარყოფილია არასაკმარისი საკრედიტო ლიმიტის გამო")
