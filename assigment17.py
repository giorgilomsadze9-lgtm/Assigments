# აქ უნდა შეიქმნას შვილი კლასი რომელიც მიიღებს მშობელი კლასისგან ყველა თვისებას. 
class SavingsAccount (BankAccount):
    def __init__(self, card_type, owner, balance, interest_rate = 5):
    #აქ უნდა შემოვიყვანო super() რადგაჰნ მშობელი კლასიდან წამოვიღო __init__ ის მონაცემები და არ ვწერო თავიდან ბარათის და ბალანსის მონაცემები.
        super().__init__(card_type, owner, balance)
        #ვამატებ მხოლოდ ანაბრის პროცენტისთვის ატრიბუტს
        self.interest_rate = interest_rate
        # აქ მჭირდება მეთოდის დამატება, რომელიც ნაშთზე დაარიცხავს %-ს და გაზრდის ბალანსს. 
    def accrual_of_interest(self):
        # ეს მეთოდი მოახდენს პროცენტის დარიცხვას არსებულ ნაშთზე
        interest_amount = self.balance * self.interest_rate / 100
        # აქ უნდა გამოვიყენოთ მშობელი კლასის deposit-ს ფუნქცია და დავპრინტოთ რამდენი დაირიცხა
        self.deposit(interest_amount)
        print (f" დაირიცხა სარგებელი {interest_amount} ლარი  ")
# აქ დაგვჭირდება პლიმორფიზმი თანხის გატანისთვის და გვჭირდება გადაფარვა.ვ
    def withdraw(self, amount):
        #აქ უნდა შევცვალოთ და გადავფაროთ მშობლის მეთოდი თანხის მოხსნისას უნდა ჩამოიჭრას 2 ლარიანი საკომისიო. 
        fee = 2 
        total_reduced = amount + fee
        #აქ ბალანსს უნდა გამოვაკლოთ საკომისიოს და გასატანი თანხის ჯამი
        if  0 < total_reduced <= self.balance:
            self.balance = self.balance - total_reduced
            print (f" ანგარიშიდან მოხსნილია {amount} ლარი, (+ {fee} ლარი გატანის საკომისიო). დარჩენილია: {self.balance} ლარი. ")
        else:
            print(" დანაზოგის ანგარიშიდან თანხა ვერ მოიხსნა არასაკმაირის რაოდენობის გამო. ") 

