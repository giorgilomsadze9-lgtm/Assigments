# ვქმნი მშობელ კლასს 
class BankAccount:
    #აქ იქმნება კლასის ატრიბუტი, რომელიც საერთო უნდა იყოს ყველა საბანკო ანგარიშისთვის
    bank_name = "BB" #ბაზისბანკი
    #აქ ვქმნი კონსტრუქტორს რომელიც აქტიურდება მაშნვე როცა ახალ ანგარიშს შევქმნი
    def __init__(self, card_type, owner, balance):
        self.card_type = card_type #საჯარო ატრიბუტი
        self.owner = owner         #საჯარო ატრიბუტი
        self.__balance = balance #დახურული ატრიბუტი აუცილებლად 2 დაბლა ტირეთი, რომ გარედან არავინ შეცვალოს.
# უსაფრთხოდ მართვისთვის მჭირდება შემდეგი ფუნქციების შემოყვანა @property (Getter, Setter, Deleter).
# აქ როცა ბალანსის წაკითხვა დაგვჭირდება პროგრამა უსაფრთხოდა დააბრუნებს ბალანსს return-ის გამოყენებით და დაბლა ტირეებით ბალანსს. 
    @property
    def balance(self):
        return self.__balance
    #აქ დავამატებ ბალანსის setter ფუნქციას რადგან შევცვალო ბალანსი ან შევავსო
    @balance.setter
    def balance(self, amount):
    #აქ უნდა ჩავაშენო პირობა რომ ბალანსი არასდროს არ იყოს უარყოფითი. 
        if amount >= 0:
            self.__balance = amount 
        else:
            raise ValueError("შეცდომა!!!  ანგარიშზე არ არის საკმარისი თანხა ")
    # აქ შემომაქვს წაშლის ფუნქცია, იმ შემთხვევისთვის თუ  პროგრამიდან დაგვჭირდა ბალანსის ჩანაწერის წაშლა. 
    @balance.deleter
    def balance (self):
        del self.__balance
        print(" ბალანსის შესახებ ინფორმაცია წაშლილია ")
# აქ გვჭირდება ძირითადი "მეთოდები" -ს შემოტანა ფუნქციის კლასის შიგნით. 
# უნდა შემოვიტანოთ ფუნქციები თანხის შეტანის მეთოდისთვის და შევამოწმოთ არის თ არა თანხა 0 ზე მეტი და თუ კი მაშნ დაამატოს მიმდინარე ბალანსს.
    def deposit(self, amount):
        if amount > 0:
            self.__balance += amount
            print(f"თქვენ წარმატებით შეიტანეთ {amount} ლარი. მიმდინარე ბალანსი შეადგენს {self.__balance} ლარს ")
        else:
            print(" შეტანილი თანხის ნაშთი უნდა იყოს 0 -ზე მეტი! ")
# აქ უნდა შემოვიტანოთ თანხის მოხსნის მეთოდი -withdraw
    def withdraw (self, amount):
        if 0 < amount <= self.__balance:
            self.__balance -= amount
            print(f"თქვენ წარმატებით გამოიტანეთ {amount} ლარი, დარჩენილი თანხა ანგარიშზე: {self.__balance} ლარი. ")
        else:
            print(" მოთხოვნა უარყოფილია ანგარიშზე არასაკმარისი თანხის გამო :( )")
