# აქ უნდა შეიქმნას დამატებით მეთოდები ანგარიშების მართვისთვის რომელიც იქნება კიდევ ერთი შვილი კლასი @classmethod, @staticmethod, 
class Account_Management_system: # ეს არის დამხმარე კლასი და არ გვაქვს მშობლის თვისებები
    #აქ შეიქმნება  კლაისს ცვლადი რომელიც დაითვლის არსებული ანგარიშების რაოდენობას. 
    total_accounts = 0  
    @classmethod
    #@classmethod: იყენებს cls-ს (თავად კლასს) და ზრდის საერთო ანგარიშების მთვლელს 1-ით.
    def add_account_count(cls):
        cls.total_accounts += 1
    @staticmethod
    def calculate_tax(amount):
    # @staticmethod -  არის დამხმარე ფუნქცია, რომელსაც არც self სჭირდება და არც cls. ის უბრალოდ ითვლის ნებისმიერ თანხაზე ამ შემთხვევაშ 20%-იან გადასახადს
        tax = amount * 0.2
        return tax
    




